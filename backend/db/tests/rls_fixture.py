class OrgDb:
    def __init__(self, cluster, name: str, pgb_port: int) -> None:
        self.cluster, self.name, self.pgb_port = cluster, name, pgb_port

    def admin(self, autocommit: bool = True) -> psycopg.Connection:
        return psycopg.connect(host="127.0.0.1", port=self.cluster.port, user="postgres", dbname=self.name, autocommit=autocommit)

    def pooled(self, svc: str = "node", **kw) -> psycopg.Connection:
        """A connection to the service's login through PgBouncer (transaction pooling, kernel reset)."""
        return psycopg.connect(host="127.0.0.1", port=self.pgb_port, user=f"pipeshub_{svc}_login", dbname=self.name, **kw)

    def pooled_as(self, user: str, **kw) -> psycopg.Connection:
        return psycopg.connect(host="127.0.0.1", port=self.pgb_port, user=user, dbname=self.name, **kw)

    def violations(self, conn: psycopg.Connection | None = None) -> list[tuple[str, str]]:
        if conn is None:
            with self.admin() as c:
                return self.violations(c)
        rows = [tuple(r) for r in conn.execute("SELECT rule, object FROM kernel.rls_violations ORDER BY 1, 2")]
        return rows + surface.violations(conn, [str(KT_ROLES), str(KT_SURFACE)])

    def surface_only(self, conn: psycopg.Connection) -> list[tuple[str, str]]:
        return surface.violations(conn, [str(KT_ROLES), str(KT_SURFACE)])


@contextmanager
def uow(conn: psycopg.Connection, role: str, org: str | None, lineage: str | None = None, user: str | None = None):
    """What the runtime's unit of work does: one transaction, role and org set transaction-locally, role-leak guard first."""
    with conn.transaction():
        leaked = conn.execute("SELECT current_setting('role')").fetchone()[0]
        assert leaked == "none", f"session role leaked: {leaked}"
        conn.execute("SELECT set_config('role', %s, true), set_config('app.org_id', %s, true), set_config('app.org_lineage', %s, true), "
                     "set_config('app.user_id', %s, true)", (role, org or "", lineage or "", user or ""))
        yield conn


def start_pgbouncer(binary: str, cluster, name: str, root: Path, port: int, pool: int = 2) -> subprocess.Popen:
    (root / "users.txt").write_text("".join(f'"pipeshub_{s}_login" ""\n' for s in LOGINS) + '"pipeshub_jobs" ""\n"pipeshub_ro" ""\n')
    (root / "pgb.ini").write_text(f"""[databases]
{name} = host=127.0.0.1 port={cluster.port} dbname={name}
[pgbouncer]
listen_addr = 127.0.0.1
listen_port = {port}
unix_socket_dir =
pool_mode = transaction
auth_type = trust
auth_file = {root}/users.txt
server_reset_query = {KERNEL_RESET}
server_reset_query_always = 1
max_prepared_statements = 200
server_login_retry = 1
max_client_conn = 200
max_db_connections = {pool}
default_pool_size = {pool}
ignore_startup_parameters = extra_float_digits
pidfile = {root}/pgb.pid
logfile = {root}/pgb.log
""")
    p = subprocess.Popen([binary, str(root / "pgb.ini")], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    p.port = port
    for _ in range(100):
        try:
            psycopg.connect(host="127.0.0.1", port=port, user="pipeshub_node_login", dbname=name).close()
            return p
        except psycopg.Error:
            time.sleep(0.1)
    p.terminate()
    raise RuntimeError("pgbouncer did not start")

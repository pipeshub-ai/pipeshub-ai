-- Ids are 24-hex ObjectId strings; org_id is plain text. A column that is NULL is a key the row mapper leaves out.
CREATE DOMAIN platform.oid24 AS text COLLATE "C" CHECK (VALUE ~ '^[0-9a-f]{24}$');

-- Notifications and the mail log grow without bound, so they are RANGE partitions by month of created_at: a month is dropped whole
-- once it is past retention (python -m db.maintain monthly). The DEFAULT partition takes a row whose month has no partition yet.
CREATE TABLE platform.notifications (
  org_id text NOT NULL,
  id platform.oid24 NOT NULL,
  created_at timestamptz NOT NULL,
  type text NOT NULL,
  title text,
  message text,
  redirect_link text,
  severity text CHECK (severity IN ('info', 'warning', 'error', 'critical', 'success')),
  status text NOT NULL DEFAULT 'unread' CHECK (status IN ('read', 'unread', 'archived')),
  origin_service text CHECK (origin_service IN ('Connector Service', 'Indexing Service', 'AI Service', 'External Service')),
  assigned_to platform.oid24 NOT NULL,
  payload jsonb,
  is_deleted boolean NOT NULL DEFAULT false,
  deleted_by platform.oid24,
  version int NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (org_id, created_at, id)
) PARTITION BY RANGE (created_at);

CREATE TABLE platform.mail_log (
  org_id text NOT NULL,
  id platform.oid24 NOT NULL,
  created_at timestamptz NOT NULL,
  subject text,
  from_address text NOT NULL,
  to_addresses text[] NOT NULL,
  cc_addresses text[] NOT NULL DEFAULT '{}',
  email_template_type text NOT NULL,
  version int NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (org_id, created_at, id)
) PARTITION BY RANGE (created_at);

DO $$
DECLARE t text; m date; i int;
BEGIN
  FOREACH t IN ARRAY ARRAY['notifications', 'mail_log'] LOOP
    EXECUTE format('CREATE TABLE platform.%1$s_def PARTITION OF platform.%1$s DEFAULT', t);
    -- the previous month (late-arriving rows) and the next three
    FOR i IN -1..3 LOOP
      m := (date_trunc('month', now() AT TIME ZONE 'UTC') + make_interval(months => i))::date;
      EXECUTE format('CREATE TABLE platform.%1$s_%2$s PARTITION OF platform.%1$s FOR VALUES FROM (%3$L) TO (%4$L)', t, to_char(m, '"y"YYYY"m"MM'),
                     m::timestamp AT TIME ZONE 'UTC', (m + interval '1 month')::timestamp AT TIME ZONE 'UTC');
    END LOOP;
  END LOOP;
END $$;

-- the inbox, newest first; the by-id lookup probes one index per month (ids are app-generated, unique by construction)
CREATE INDEX notifications_inbox ON platform.notifications (org_id, assigned_to, status, created_at DESC, id DESC) WHERE NOT is_deleted;
CREATE INDEX notifications_by_id ON platform.notifications (org_id, id);

CREATE TABLE platform.connectors_config (
  org_id text NOT NULL,
  name text NOT NULL,
  id platform.oid24 NOT NULL,
  is_enabled boolean NOT NULL DEFAULT true,
  last_updated_by platform.oid24 NOT NULL,
  version int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (org_id, name),
  UNIQUE (org_id, id)
);

-- Events decided with a change and delivered to the broker afterwards. A request appends in its own unit (so inside the change's
-- transaction); the dispatcher, a job, claims and settles rows of every org.
CREATE TABLE platform.outbox (
  org_id text NOT NULL,
  id bigint GENERATED BY DEFAULT AS IDENTITY,
  topic text NOT NULL,
  msg_key text NOT NULL,
  ordering_key text NOT NULL DEFAULT 'global',
  value text NOT NULL,
  headers jsonb,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'publishing', 'published', 'failed')),
  attempts int NOT NULL DEFAULT 0,
  next_attempt_at timestamptz NOT NULL,
  claimed_at timestamptz,
  last_error text,
  published_at timestamptz,
  version int NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL,
  updated_at timestamptz NOT NULL,
  PRIMARY KEY (org_id, id)
);
-- the next due row, oldest first
CREATE INDEX outbox_due ON platform.outbox (created_at, id) WHERE status IN ('pending', 'publishing');
-- "is anything older about this entity still undelivered?"
CREATE INDEX outbox_by_ordering_key ON platform.outbox (ordering_key, created_at) WHERE status IN ('pending', 'publishing', 'failed');
-- the dispatcher settles a row by its id alone
CREATE INDEX outbox_by_id ON platform.outbox (id);
CREATE INDEX outbox_published ON platform.outbox (published_at) WHERE status = 'published';


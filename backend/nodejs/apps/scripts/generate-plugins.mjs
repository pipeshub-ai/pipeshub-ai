#!/usr/bin/env node
/**
 * Writes src/plugins.generated.ts: the list of plug-ins this build contains.
 *
 *   node scripts/generate-plugins.mjs                 every directory under src/plugins
 *   node scripts/generate-plugins.mjs a b             only plug-ins a and b
 *   node scripts/generate-plugins.mjs --none          no plug-ins
 *   PLATFORM_PLUGINS="a,b" node scripts/generate-plugins.mjs   same, from the environment
 *   PLATFORM_PLUGINS="" node scripts/generate-plugins.mjs      no plug-ins
 *
 * Options: --src <dir> (default: ../src next to this script), --check (exit 1
 * when the file on disk differs from what would be written, write nothing).
 *
 * An image that must not contain a plug-in deletes src/plugins/<name> and runs
 * this with no arguments (or with --none) before compiling.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const NAME = /^[a-z][a-z0-9-]*$/;

function fail(message) {
  process.stderr.write(`generate-plugins: ${message}\n`);
  process.exit(2);
}

const args = process.argv.slice(2);
let srcDir = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'src');
let check = false;
let none = false;
const named = [];
for (let i = 0; i < args.length; i++) {
  const arg = args[i];
  if (arg === '--src') {
    const value = args[++i];
    if (value === undefined) fail('--src needs a directory');
    srcDir = resolve(value);
  } else if (arg === '--check') check = true;
  else if (arg === '--none') none = true;
  else if (arg.startsWith('--')) fail(`unknown option ${arg}`);
  else named.push(...arg.split(','));
}

const pluginsDir = join(srcDir, 'plugins');
const isPlugin = (name) => existsSync(join(pluginsDir, name, 'index.ts'));

let names;
if (none) names = [];
else if (named.length > 0) names = named;
else if (process.env.PLATFORM_PLUGINS !== undefined)
  names = process.env.PLATFORM_PLUGINS.split(/[\s,]+/);
else
  names = existsSync(pluginsDir)
    ? readdirSync(pluginsDir, { withFileTypes: true })
        .filter((entry) => entry.isDirectory() && isPlugin(entry.name))
        .map((entry) => entry.name)
    : [];

names = [...new Set(names.map((n) => n.trim()).filter((n) => n !== ''))].sort();
for (const name of names) {
  if (!NAME.test(name)) fail(`"${name}" is not a plug-in name (${NAME})`);
  if (!isPlugin(name)) fail(`src/plugins/${name}/index.ts does not exist`);
}

const identifier = (name) =>
  `${name.replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase())}Plugin`;

const lines = [
  '// GENERATED by scripts/generate-plugins.mjs. Do not edit by hand.',
  '// The plug-ins this build contains; `loadPlugins()` registers them in this order.',
  "import type { PlatformPlugin } from './libs/plugins/types';",
  ...names.map((n) => `import ${identifier(n)} from './plugins/${n}';`),
  '',
  names.length === 0
    ? 'export const plugins: readonly PlatformPlugin[] = [];'
    : `export const plugins: readonly PlatformPlugin[] = [\n${names
        .map((n) => `  ${identifier(n)},\n`)
        .join('')}];`,
  '',
];
const content = lines.join('\n');
const target = join(srcDir, 'plugins.generated.ts');

if (check) {
  const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
  if (current !== content) {
    process.stderr.write(
      `generate-plugins: ${target} is out of date; run node scripts/generate-plugins.mjs\n`,
    );
    process.exit(1);
  }
} else {
  writeFileSync(target, content);
  process.stdout.write(
    `generate-plugins: wrote ${names.length} plug-in(s) to ${target}\n`,
  );
}

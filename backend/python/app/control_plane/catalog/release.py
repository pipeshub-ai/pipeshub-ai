"""Build the release catalog from the registered sources and render it as files.

Nothing here knows a kind: sources are taken as given (OCP), checked only against
rules every kind shares.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from typing import TYPE_CHECKING, cast

from pydantic import ValidationError

from app.control_plane.contracts.generated.catalog_item import CatalogItem

if TYPE_CHECKING:
    from collections.abc import Mapping, Sequence
    from pathlib import Path

    from app.control_plane.catalog.items import ReleaseItem
    from app.control_plane.catalog.ports import ReleaseItemSource

GENERATED_BY = "python -m app.control_plane.catalog.dump --write"


class ReleaseCatalogError(ValueError):
    reason = "release_catalog_invalid"


@dataclass(frozen=True, slots=True)
class KindCatalog:
    kind: str
    catalog_file: str
    items: tuple[ReleaseItem, ...]


def build_release_catalog(sources: Sequence[ReleaseItemSource]) -> tuple[KindCatalog, ...]:
    kinds: set[str] = set()
    files: set[str] = set()
    refs: set[str] = set()
    built: list[KindCatalog] = []
    for source in sources:
        if source.kind in kinds:
            raise ReleaseCatalogError(f"two sources for kind {source.kind}")
        if source.catalog_file in files:
            raise ReleaseCatalogError(f"two sources write {source.catalog_file}")
        kinds.add(source.kind)
        files.add(source.catalog_file)
        items = sorted(source.items(), key=lambda item: str(item.ref))
        for item in items:
            ref = str(item.ref)
            if item.kind != source.kind:
                raise ReleaseCatalogError(f"source {source.kind} produced {ref}")
            if ref in refs:
                raise ReleaseCatalogError(f"{ref} appears twice")
            try:
                _ = CatalogItem.model_validate(item.to_json())
            except ValidationError as exc:
                raise ReleaseCatalogError(f"{ref} is not a valid catalog item: {exc.errors()[0]['msg']}") from exc
            refs.add(ref)
        built.append(KindCatalog(source.kind, source.catalog_file, tuple(items)))
    return tuple(built)


def _document(catalog: KindCatalog) -> str:
    document = {
        "generatedBy": GENERATED_BY,
        "kind": catalog.kind,
        "items": [item.to_json() for item in catalog.items],
    }
    return json.dumps(document, indent=2, ensure_ascii=False) + "\n"


def render_release_files(catalogs: Sequence[KindCatalog]) -> dict[str, str]:
    return {catalog.catalog_file: _document(catalog) for catalog in catalogs}


def render_node_module(catalogs: Sequence[KindCatalog]) -> str:
    """Node compiles only ``src``, so it gets the same items as a module: one JSON text per kind."""
    lines = [
        f"// Generated by `{GENERATED_BY}` from the release registries. Do not edit.",
        "// Equal, item for item, to contracts/control-plane/catalog/*.json (CPD2-31).",
        "export const RELEASE_CATALOG_JSON: Readonly<Record<string, string>> = {",
    ]
    for catalog in catalogs:
        items = json.dumps([item.to_json() for item in catalog.items], ensure_ascii=False, separators=(",", ":"))
        lines.append(f"  {json.dumps(catalog.kind)}:\n    {json.dumps(items, ensure_ascii=False)},")
    lines.append("};")
    return "\n".join(lines) + "\n"


def stale_files(targets: Mapping[Path, str]) -> list[Path]:
    return sorted(
        path for path, text in targets.items() if not path.exists() or path.read_text(encoding="utf-8") != text
    )


def catalog_drift(catalogs: Sequence[KindCatalog], directory: Path) -> list[str]:
    """Each ref added, removed or changed against the committed files, as ``file: verb ref``."""
    drift: list[str] = []
    for catalog in catalogs:
        path = directory / catalog.catalog_file
        committed = cast(
            "list[dict[str, object]]", json.loads(path.read_text(encoding="utf-8"))["items"] if path.exists() else []
        )
        before = {str(item["ref"]): item for item in committed}
        after = {str(item.ref): item.to_json() for item in catalog.items}
        drift.extend(f"{catalog.catalog_file}: added {ref}" for ref in sorted(after.keys() - before.keys()))
        drift.extend(f"{catalog.catalog_file}: removed {ref}" for ref in sorted(before.keys() - after.keys()))
        drift.extend(
            f"{catalog.catalog_file}: changed {ref}"
            for ref in sorted(after.keys() & before.keys())
            if after[ref] != before[ref]
        )
        if not drift and path.exists() and path.read_text(encoding="utf-8") != _document(catalog):
            drift.append(f"{catalog.catalog_file}: not in the dump's format")
    return drift

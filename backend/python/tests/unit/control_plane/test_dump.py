"""CPD2-24..CPD2-28: the release catalog build and its files."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field, replace
from pathlib import Path

import pytest

from app.control_plane.catalog.dump import main
from app.control_plane.catalog.items import Display, ReleaseItem, ToolDescriptor
from app.control_plane.catalog.release import (
    ReleaseCatalogError,
    build_release_catalog,
    render_release_files,
    stale_files,
)

REPO = Path(__file__).resolve().parents[5]
CATALOG_DIR = REPO / "contracts/control-plane/catalog"
TOKEN_PATTERNS = json.loads((REPO / "contracts/harness/vectors/token-patterns.json").read_text(encoding="utf-8"))


def _item(kind: str, name: str, *, description: str = "d") -> ReleaseItem:
    return ReleaseItem(
        kind=kind,
        name=name,
        display=Display(name=name.title(), description=description),
        descriptor_kind="tool",
        descriptors=(ToolDescriptor(name="t", description="t", input_schema={"type": "object"}, effect="read"),),
    ).with_content_version()


@dataclass
class _Source:
    kind: str
    catalog_file: str
    produced: list[ReleaseItem] = field(default_factory=list)

    def items(self) -> list[ReleaseItem]:
        return list(self.produced)


def test_cpd2_24_the_build_is_deterministic_and_ordered_by_ref() -> None:
    source = _Source("widget", "widgets.json", [_item("widget", "b"), _item("widget", "a")])
    first = render_release_files(build_release_catalog([source]))
    second = render_release_files(build_release_catalog([_Source("widget", "widgets.json", list(reversed(source.produced)))]))
    assert first == second
    document = json.loads(first["widgets.json"])
    assert [item["name"] for item in document["items"]] == ["a", "b"]
    assert document["kind"] == "widget"


def test_cpd2_27_a_new_kind_is_one_more_source() -> None:
    files = render_release_files(
        build_release_catalog([_Source("widget", "widgets.json", [_item("widget", "a")]), _Source("gadget", "gadgets.json", [_item("gadget", "g")])])
    )
    assert set(files) == {"widgets.json", "gadgets.json"}


@pytest.mark.parametrize(
    ("sources", "named"),
    [
        ([_Source("widget", "w.json"), _Source("widget", "x.json")], "widget"),
        ([_Source("widget", "w.json", [_item("gadget", "a")])], "gadget:pipeshub/a"),
        ([_Source("widget", "w.json", [_item("widget", "a"), _item("widget", "a")])], "widget:pipeshub/a"),
        ([_Source("widget", "w.json"), _Source("gadget", "w.json")], "w.json"),
        ([_Source("widget", "w.json", [replace(_item("widget", "a"), risk_class="huge")])], "widget:pipeshub/a"),  # type: ignore[arg-type]
    ],
    ids=["duplicate kind", "foreign kind", "duplicate ref", "duplicate file", "invalid item"],
)
def test_cpd2_28_bad_sources_are_refused_by_name(sources: list[_Source], named: str) -> None:
    with pytest.raises(ReleaseCatalogError, match=re.escape(named)):
        build_release_catalog(sources)


def test_cpd2_25_check_names_stale_files_and_write_rewrites_only_those(tmp_path: Path) -> None:
    sources = [_Source("widget", "widgets.json", [_item("widget", "a")]), _Source("gadget", "gadgets.json", [_item("gadget", "g")])]
    targets = {tmp_path / name: text for name, text in render_release_files(build_release_catalog(sources)).items()}
    assert [p.name for p in stale_files(targets)] == ["gadgets.json", "widgets.json"]
    for path, text in targets.items():
        path.write_text(text, encoding="utf-8")
    assert stale_files(targets) == []
    (tmp_path / "widgets.json").write_text("{}", encoding="utf-8")
    assert [p.name for p in stale_files(targets)] == ["widgets.json"]


def test_cpd2_25_cli_check_and_write(tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]) -> None:
    sources = [_Source("widget", "widgets.json", [_item("widget", "a")])]
    monkeypatch.setattr("app.control_plane.catalog.dump.load_release_sources", lambda: sources)
    assert main(["--check", "--out", str(tmp_path), "--node-out", str(tmp_path / "node.ts")]) == 1
    assert "widgets.json" in capsys.readouterr().err
    assert main(["--write", "--out", str(tmp_path), "--node-out", str(tmp_path / "node.ts")]) == 0
    assert main(["--check", "--out", str(tmp_path), "--node-out", str(tmp_path / "node.ts")]) == 0
    node = (tmp_path / "node.ts").read_text(encoding="utf-8")
    assert node.startswith("// Generated by")
    assert "widgets.json" not in capsys.readouterr().err


def test_cpd2_24_render_does_not_depend_on_the_environment(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> None:
    source = _Source("widget", "widgets.json", [_item("widget", "a")])
    before = render_release_files(build_release_catalog([source]))
    monkeypatch.chdir(tmp_path)
    monkeypatch.setenv("HOSTNAME", "elsewhere")
    assert render_release_files(build_release_catalog([source])) == before


def test_cpd2_26_no_secret_in_release_data() -> None:
    paths = sorted(CATALOG_DIR.glob("*.json"))
    assert len(paths) == 4
    text = "\n".join(path.read_text(encoding="utf-8") for path in paths)
    for pattern in TOKEN_PATTERNS["patterns"]:
        assert re.search(pattern["source"], text) is None, f"release data matches {pattern['kind']}"

"""The scope filter on pgvector: off, a request renders the statements it always did; on, the condition is ANDed with the rest, every value
is a bound parameter, and what cannot be trusted admits nothing. (The behaviour against real rows is in the integration suite.)"""

from __future__ import annotations

import json
from pathlib import Path
from unittest.mock import AsyncMock, MagicMock

import pytest

from app.services.vector_db.filters import (
    ScopeFilter,
    ScopeFilterTooLarge,
    reject_scope_filter,
)
from app.services.vector_db.models import HybridSearchRequest
from app.services.vector_db.pgvector import scope_filter as scope_sql
from tests.unit.services.vector_db import pgvector_statements as stmts

GOLDEN = json.loads((Path(__file__).parent / "pgvector_statements.golden.json").read_text())


def flt(**kw: object) -> ScopeFilter:
    base = {"current": frozenset({"c1"}), "open_apps": frozenset({"c1"}), "readable_groups": frozenset({"g1"}),
            "readable_scopes": frozenset({"s1"}), "excluded": frozenset({"x1"}), "version": 5, "generation": 3}
    return ScopeFilter(**{**base, **kw})  # type: ignore[arg-type]


def test_without_a_scope_filter_every_statement_and_parameter_is_what_it_was() -> None:
    """Generated by the code before the filter existed (66 statements: dense tiers, count and lexical, for six scopes)."""
    assert stmts.render() == GOLDEN


def test_a_request_carries_no_scope_filter_unless_asked() -> None:
    assert HybridSearchRequest().scope_filter is None


def test_with_the_filter_on_it_is_anded_after_the_existing_conditions_and_changes_nothing_else() -> None:
    on = stmts.render(flt())
    assert set(on) == set(GOLDEN)
    for name, off in GOLDEN.items():
        assert on[name]["sql"] != off["sql"], name
        assert on[name]["sql"].count("retrieval.point_groups sg") == 1, name
        assert off["args"] == on[name]["args"][:len(off["args"])], name              # the old parameters keep their numbers and values
        assert len(on[name]["args"]) == len(off["args"]) + scope_sql.N_PARAMS, name


def test_the_condition_binds_every_value_and_splices_only_parameter_numbers() -> None:
    sql, params = scope_sql.predicate(flt(current=frozenset({"c1", "it's"}), readable_groups=frozenset({"g'; DROP TABLE x;--"})), 12)
    assert "DROP" not in sql and "it's" not in sql and "c1" not in sql and "g1" not in sql
    assert [f"${n}" for n in range(12, 19)] == sorted({t for t in sql.replace("::", " ").split() if t.startswith("$") and t[1:].isdigit() and int(t[1:]) >= 12},
                                                         key=lambda t: int(t[1:]))
    assert len(params) == scope_sql.N_PARAMS == 7
    assert params[0] == ["c1", "it's"] and params[5:] == [5, 3]


def test_the_condition_starts_after_the_extra_conditions_parameters() -> None:
    sql, _ = scope_sql.predicate(flt(), 14)
    assert "$14::text[]" in sql and "$20::int" in sql and "$13" not in sql and "$21" not in sql


@pytest.mark.parametrize("kw", [{"generation": -2}, {"generation": -1}, {"current": frozenset()}], ids=["unavailable", "unknown", "no connector"])
def test_a_filter_that_can_trust_nothing_admits_nothing(kw: dict) -> None:
    assert scope_sql.predicate(flt(**kw), 12) == (" AND false", [])


def test_every_admit_rule_requires_a_trusted_stamp_and_a_known_connector_set() -> None:
    sql, _ = scope_sql.predicate(flt(), 12)
    for need in ("sg.org_id = $1", "sg.collection_id = $2", "sg.group_key = p.group_key", "sg.scope_version = $17::int",
                 "sg.scope_generation = $18::int", "cardinality(sg.connector_ids) > 0", "sg.connector_ids <@ $12::text[]"):
        assert need in sql, need
    assert sql.index("AND (") > sql.index("sg.connector_ids <@")            # the rules sit inside the trust conditions, never beside them
    assert "NOT (sg.path_ids && $16::text[])" in sql


def test_too_large_a_list_is_refused_not_truncated() -> None:
    with pytest.raises(ScopeFilterTooLarge):
        flt(readable_groups=frozenset(str(i) for i in range(100_001))).lists()


def test_the_sorted_lists_are_computed_once_per_filter(monkeypatch: pytest.MonkeyPatch) -> None:
    f = flt()
    calls: list[int] = []
    real = sorted
    monkeypatch.setattr("builtins.sorted", lambda x, *a, **k: (calls.append(1), real(x, *a, **k))[1])
    first = f.lists()
    assert len(calls) == 5 and f.lists() is first and scope_sql.predicate(f, 12) and len(calls) == 5   # later calls (statement, key, args) sort nothing
    assert first == (["c1"], ["c1"], ["g1"], ["c1", "g1", "s1"], ["x1"])


@pytest.mark.parametrize("store", ["Qdrant", "OpenSearch", "Redis"])
def test_a_store_that_cannot_translate_the_filter_refuses_the_request(store: str) -> None:
    with pytest.raises(NotImplementedError):
        reject_scope_filter([HybridSearchRequest(), HybridSearchRequest(scope_filter=flt())], store)
    reject_scope_filter([HybridSearchRequest()], store)


@pytest.mark.asyncio
async def test_the_other_providers_call_the_refusal_before_they_search() -> None:
    from app.services.vector_db.opensearch.opensearch import OpenSearchService
    from app.services.vector_db.qdrant.qdrant import QdrantService
    from app.services.vector_db.redis.redis_vector import RedisVectorService

    for cls in (QdrantService, OpenSearchService, RedisVectorService):
        svc = cls.__new__(cls)
        svc._assert_connected = AsyncMock() if cls is OpenSearchService else MagicMock()          # type: ignore[method-assign]
        svc.client = MagicMock()
        with pytest.raises(NotImplementedError):
            await svc.query_nearest_points("c", [HybridSearchRequest(dense_query=[1.0], scope_filter=flt())])

# ---- the reference rule: the pgvector SQL, written out again from its text ----

def pg_rule(f: ScopeFilter, p: dict) -> bool:
    """`pgvector/scope_filter.py`, as Python over a point's fields."""
    if f.generation < 0 or not f.current:
        return False
    c, stamp = set(p.get("connectorIds") or []), p.get("scopeStamp")
    if p.get("scopeFieldsVersion") != f.version or p.get("scopeGeneration") != f.generation or not c or not c <= f.current:
        return False
    groups, reach = f.readable_groups, f.readable_groups | f.readable_scopes | f.open_apps
    path, acl = set(p.get("pathIds") or []), set(p.get("aclScope") or [])
    return bool(
        (stamp == "container" and (set(p.get("recordGroupIds") or []) & groups or set(p.get("rootRecordGroupIds") or []) & groups or c & f.open_apps))
        or (stamp in ("container", "union", "intersection", "override") and acl & reach)
        or (stamp in ("union", "intersection") and path & reach and not path & f.excluded))


def random_world(rng: random.Random) -> tuple[ScopeFilter, list[dict]]:
    ids = ["a", "b", "c", "d"]
    pick = lambda: frozenset(rng.sample(ids, rng.randint(0, 3)))  # noqa: E731
    f = ScopeFilter(pick() or frozenset({"a"}), pick(), pick(), pick(), pick(), rng.choice([5, 5, 5, 4]), rng.choice([3, 3, 3, 2, -1]))
    stamps = ["container", "union", "intersection", "override", "legacy", "weird", None]
    points = []
    for _ in range(40):
        p = {k: rng.sample(ids, rng.randint(0, 3)) for k in ("connectorIds", "recordGroupIds", "rootRecordGroupIds", "pathIds", "aclScope")}
        if rng.random() < 0.9:
            p.update(scopeStamp=rng.choice(stamps), scopeFieldsVersion=rng.choice([5, 5, 5, 4, None]), scopeGeneration=rng.choice([3, 3, 3, 2, None]))
        for k in list(p):
            if rng.random() < 0.1:
                del p[k]
        points.append(p)
    return f, points


def test_the_tree_admits_exactly_what_the_pgvector_rule_admits_on_random_worlds() -> None:
    rng = random.Random(7)
    admitted = 0
    for _ in range(1500):
        f, points = random_world(rng)
        node = sx.admits(f)
        for p in points:
            assert sx.evaluate(node, p) is bool(pg_rule(f, p)), (f, p)
            admitted += pg_rule(f, p)
    assert admitted > 400                                   # the worlds exercise the admitting branches, not only the refusing ones


# ---- on: the translation ----

def walk(obj: object):  # noqa: ANN201
    yield obj
    if isinstance(obj, dict):
        for v in obj.values():
            yield from walk(v)
    elif isinstance(obj, list):
        for v in obj:
            yield from walk(v)


async def test_qdrant_ands_the_translation_with_the_requests_own_filter() -> None:
    plain = (await sr.captured("qdrant", [sr.plain_requests()["dense_text_arms"]]))[0]
    [req] = await sr.captured("qdrant", [scoped()])
    assert req["filter"]["must"][0] == plain["filter"]                          # the request's own filter, whole, first
    assert len(req["filter"]["must"]) == 2 and req["filter"]["should"] is None and req["filter"]["must_not"] is None
    texts = json.dumps(req["filter"]["must"][1])
    assert '"except' in texts and "scopeFieldsVersion" in texts and "scopeGeneration" in texts and "connectorIds" in texts
    only = (await sr.captured("qdrant", [scoped("no_filter")]))[0]                  # no filter of its own: the translation stands alone
    assert len(only["filter"]["must"]) == 1


async def test_qdrant_never_uses_an_empty_should_which_matches_everything() -> None:
    for f in (flt(), flt(current=frozenset()), flt(generation=-2), flt(readable_groups=frozenset(), readable_scopes=frozenset(), open_apps=frozenset())):
        [req] = await sr.captured("qdrant", [scoped("no_filter", f)])
        assert not [n for n in walk(req["filter"]) if isinstance(n, dict) and n.get("should") == []], f
        assert not [n for n in walk(req["filter"]) if isinstance(n, dict) and n.get("must") == [] and len(n) > 3 and False]
    [nothing] = await sr.captured("qdrant", [scoped("no_filter", flt(generation=-2))])
    assert nothing["filter"]["must"][0]["match"]["any"] == []                       # a match on an empty list: nothing


async def test_opensearch_keeps_the_requests_filter_whole_inside_must_and_the_translation_in_filter() -> None:
    [plain] = await sr.captured("opensearch", [sr.plain_requests()["dense_text_arms"]])
    [req] = await sr.captured("opensearch", [scoped()])
    hybrid = req["kwargs"]["body"]["query"]["hybrid"]["queries"]
    knn = next(q for q in hybrid if "knn" in q)["knn"]["dense_embedding"]["filter"]
    assert knn["bool"]["must"] == [plain["kwargs"]["body"]["query"]["hybrid"]["queries"][1]["knn"]["dense_embedding"]["filter"]]
    assert "terms_set" in json.dumps(knn["bool"]["filter"]) and "scopeGeneration" in json.dumps(knn["bool"]["filter"])
    bm25 = next(q for q in hybrid if "bool" in q)["bool"]
    assert bm25["filter"][0] == knn                                                   # both legs carry the same filter


async def test_opensearch_matches_nothing_with_match_none_never_an_empty_bool() -> None:
    for f in (flt(current=frozenset()), flt(generation=-1)):
        [req] = await sr.captured("opensearch", [scoped("dense_only", f)])
        assert {"match_none": {}} in list(walk(req["kwargs"]["body"])), f
    [req] = await sr.captured("opensearch", [scoped("dense_only", flt(readable_groups=frozenset(), readable_scopes=frozenset(), open_apps=frozenset()))])
    assert not [n for n in walk(req["kwargs"]["body"]) if isinstance(n, dict) and n.get("terms") and not any(n["terms"].values())]   # no empty terms list


def redis_filters(cmds: list) -> tuple[str, str]:
    cmd = next(c for c in cmds if c[0] in ("FT.HYBRID", "FT.SEARCH"))
    return cmd[3], cmd[cmd.index("FILTER") + 1] if "FILTER" in cmd else ""


async def test_redis_ands_the_translation_with_the_requests_own_filter_on_both_legs_and_reads_the_connectors_once() -> None:
    cmds = await sr.captured("redis", [scoped()], tagvals=[b"c1", b"c2", b"c9"])
    assert [c for c in cmds if c[0] == "FT.TAGVALS"] == [["FT.TAGVALS", "col_idx", "connectorIds"]]
    search, knn = redis_filters(cmds)
    assert knn.startswith("(@metadata_orgId:{aaaaaaaaaaaaaaaaaaaaaaaa} ((@recordGroupIds:{g1|g2})|(@connectorIds:{c1}))) ")      # own filter, parenthesised
    assert search.startswith("hello ") and search.endswith(knn)                            # the lexical leg carries the same filter
    assert "@scopeFieldsVersion:[5 5]" in knn and "@scopeGeneration:[3 3]" in knn
    assert "@connectorIds:{c1} -@connectorIds:{c2|c9}" in knn                                 # every connector current: none outside it


async def test_redis_matches_nothing_in_its_own_idiom_and_asks_the_index_nothing() -> None:
    for f in (flt(current=frozenset()), flt(generation=-2)):
        cmds = await sr.captured("redis", [scoped("dense_only", f)])
        assert not [c for c in cmds if c[0] == "FT.TAGVALS"]
        assert "(@metadata_orgId:{x} -@metadata_orgId:{x})" in redis_filters(cmds)[1]
    cmds = await sr.captured("redis", [scoped("dense_only", flt(readable_groups=frozenset(), readable_scopes=frozenset(), open_apps=frozenset()))])
    assert "{}" not in redis_filters(cmds)[1]                                                   # an empty tag list is a syntax error, not "nothing"


async def test_redis_escapes_every_id_it_puts_into_the_query() -> None:
    nasty = "a-b.c|d}e{f g,h"
    cmds = await sr.captured("redis", [scoped("dense_only", flt(readable_groups=frozenset({nasty})))], tagvals=[b"c1"])
    knn = redis_filters(cmds)[1]
    assert r"a\-b\.c\|d\}e\{f\ g\,h" in knn and nasty not in knn



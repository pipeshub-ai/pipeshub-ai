def flt(**kw: object) -> ScopeFilter:
    base = {"current": frozenset({"c1"}), "open_apps": frozenset({"c1"}), "readable_groups": frozenset({"g1"}),
            "readable_scopes": frozenset({"s1"}), "excluded": frozenset({"x1"}), "version": VERSION, "generation": GENERATION}
    return ScopeFilter(**{**base, **kw})  # type: ignore[arg-type]


def scoped(name: str = "dense_text_arms", f: ScopeFilter | None = None) -> HybridSearchRequest:
    import dataclasses

    return dataclasses.replace(sr.plain_requests()[name], scope_filter=f or flt())



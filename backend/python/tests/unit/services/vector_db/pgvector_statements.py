"""Every statement a pgvector search builds from a scope, with its bound parameters, for a matrix of scopes. The golden file next to it
was generated by the code before the scope filter existed; a request without a scope filter must render exactly the same text."""

from __future__ import annotations

from app.services.vector_db.models import FieldCondition, FilterExpression
from app.services.vector_db.pgvector import dense, lexical
from app.services.vector_db.pgvector.visibility import Scope, scope_of

ORG = "a" * 24


def _must(**kw: str) -> list[FieldCondition]:
    return [FieldCondition(key="metadata.orgId", value=ORG), *[FieldCondition(key=f"metadata.{k}", value=v) for k, v in kw.items()]]


def scopes(scope_filter: object = None) -> dict[str, Scope]:
    def of(expr: FilterExpression) -> Scope:
        return scope_of(expr, scope_filter) if scope_filter is not None else scope_of(expr)

    arms = [FieldCondition(key="connectorIds", values=["c1", "c2"]), FieldCondition(key="recordGroupIds", values=["g1"]),
            FieldCondition(key="rootRecordGroupIds", values=["r1"]), FieldCondition(key="metadata.virtualRecordId", values=["v1"])]
    return {
        "whole_org": of(FilterExpression(must=_must())),
        "arms": of(FilterExpression(must=_must(), should=arms)),
        "apps_only": of(FilterExpression(must=_must(), should=arms[:1])),
        "narrowed": of(FilterExpression(must=[*_must(), FieldCondition(key="metadata.virtualRecordId", values=["v1", "v2"])], should=arms[1:3])),
        "extra": of(FilterExpression(must=[*_must(), FieldCondition(key="metadata.kind", value="k")], should=arms[:2])),
        "empty_arm": of(FilterExpression(must=_must(), should=[FieldCondition(key="connectorIds", values=[])])),
    }


def render(scope_filter: object = None) -> dict[str, dict]:
    """``name -> {"sql": ..., "args": [...]}``."""
    out: dict[str, dict] = {}
    for name, scope in scopes(scope_filter).items():
        for anti in (False, True):
            q = dense.Query(ORG, 3, 5, 8, "cosine", "[0.5,-0.25]", scope, 20, anti=anti)
            tag = f"{name}/{'anti' if anti else 'hashed'}"
            for fn, sql in (("exact", dense.exact_sql(q)), ("index", dense.index_sql(q)), ("bounded_narrow", dense.bounded_sql(q, narrow=True)),
                            ("bounded_probe", dense.bounded_sql(q, narrow=False)), ("count", dense.count_sql(q))):
                out[f"{tag}/{fn}"] = {"sql": sql, "args": [repr(a) for a in q.args(20, 10)]}
        extra, params = scope.extra_sql(first_param=11)
        out[f"{name}/lexical"] = {"sql": lexical.lexical_sql(extra), "args": [repr(p) for p in params], "asked": lexical.rows_asked(20, scope, _TUNING)}
    return out


class _T:
    lexical_overfetch = 4


_TUNING = _T()

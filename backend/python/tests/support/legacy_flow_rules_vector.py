"""Generates ``contracts/harness/vectors/legacy-flow-rules.json`` (CPD-10 LEG-P): the flow rules today's loop
applies for each approvals vector under each deployment flow setting, as the query service's read path decides
them (``refusing_flow_rules``, QA10-F1).

Node's signer must put the same rules in ``X-PipesHub-Resolved``: the header's ``flow`` met with the deployment's
own rule decides as these do. Run ``python -m tests.support.legacy_flow_rules_vector`` from ``backend/python`` to
rewrite the file; a test holds the committed file equal to ``build()``.
"""

from __future__ import annotations

import json
import os
from contextlib import contextmanager
from pathlib import Path
from typing import TYPE_CHECKING, Any

from app.control_plane.runtime.deployment import FLOW_ABOVE_ENV, FLOW_LEVEL_ENV
from app.harness.approvals import UNREADABLE_LAYER, approval_policy
from app.harness.unpinned import flow_rule, refusing_flow_rules
from harness_core.logs import HarnessLog

if TYPE_CHECKING:
    from collections.abc import Iterator

    from harness_core.effects.flow import FlowRule

VECTORS = Path(__file__).resolve().parents[4] / "contracts" / "harness" / "vectors"
VECTOR_PATH = VECTORS / "legacy-flow-rules.json"
APPROVALS_PATH = VECTORS / "approvals.json"
FLOW_GUARD_ENV = "HARNESS_FLOW_GUARD"

# The settings LEG-P's parity test runs under (tests/unit/harness/legacy/test_legacy_parity.py).
DEPLOYMENTS: dict[str, dict[str, str]] = {
    "guard off": {FLOW_GUARD_ENV: "false"},
    "guard on": {FLOW_GUARD_ENV: "true"},
    "deny above private": {FLOW_GUARD_ENV: "true", FLOW_LEVEL_ENV: "deny", FLOW_ABOVE_ENV: "private"},
    "ask above private": {FLOW_GUARD_ENV: "true", FLOW_ABOVE_ENV: "private"},
}

_DESCRIPTION = (
    "CPD-10 LEG-P cross-language vector: the flow rules today's loop applies to one request, for each document of "
    "approvals.json (by id, with that case's orgId and agentKey) under each deployment flow setting. 'rules' is "
    "the query service's read path (refusing_flow_rules: the deployment's rule and every layer's, the strictest "
    "of them; a layer it cannot read counts as ask above public, QA10-F1), and 'unreadable' says whether the "
    "case has such a layer. Node's X-PipesHub-Resolved must carry rules that, met with the deployment's own "
    "('rule'), are exactly these. 'settings' are the environment values as Node's deploymentFlow reads them. "
    "Generated by backend/python/tests/support/legacy_flow_rules_vector.py."
)
_LOG = HarnessLog.named("tests.legacy_flow_rules_vector")


@contextmanager
def _environment(values: dict[str, str]) -> Iterator[None]:
    names = (FLOW_GUARD_ENV, FLOW_LEVEL_ENV, FLOW_ABOVE_ENV)
    before = {name: os.environ.get(name) for name in names}
    try:
        for name in names:
            os.environ.pop(name, None)
        os.environ.update(values)
        yield
    finally:
        for name, value in before.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value


def _wire(rule: FlowRule) -> dict[str, str]:
    return {"level": rule.level, "above": rule.above}


def _settings(env: dict[str, str]) -> dict[str, Any]:
    settings: dict[str, Any] = {"guard": env[FLOW_GUARD_ENV] == "true"}
    if FLOW_LEVEL_ENV in env:
        settings["level"] = env[FLOW_LEVEL_ENV]
    if FLOW_ABOVE_ENV in env:
        settings["above"] = env[FLOW_ABOVE_ENV]
    return settings


def build() -> dict[str, Any]:
    documents: list[dict[str, Any]] = json.loads(APPROVALS_PATH.read_text(encoding="utf-8"))["documents"]
    deployments: list[dict[str, Any]] = []
    cases: list[dict[str, Any]] = [{"id": case["id"], "rules": {}} for case in documents]
    for name, env in DEPLOYMENTS.items():
        with _environment(env):
            deployment = flow_rule(_LOG)
            deployments.append(
                {"id": name, "settings": _settings(env), "rule": None if deployment is None else _wire(deployment)}
            )
            for case, found in zip(documents, cases, strict=True):
                policy = approval_policy(case["document"], org_id=case["orgId"], agent_key=case["agentKey"], log=_LOG)
                found["unreadable"] = any(layer is UNREADABLE_LAYER for layer in policy.layers)
                found["rules"][name] = [_wire(rule) for rule in refusing_flow_rules(policy, _LOG)]
    return {"description": _DESCRIPTION, "deployments": deployments, "cases": cases}


def render() -> str:
    return json.dumps(build(), indent=2) + "\n"


if __name__ == "__main__":
    VECTOR_PATH.write_text(render(), encoding="utf-8")

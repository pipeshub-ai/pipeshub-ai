"""Generates ``contracts/control-plane/vectors/resolved-turn.json`` (CPD-10 RTE-22): the tokens Node's signer and
the query service's verifier must agree on.

Deterministic: Ed25519 signatures are, the keys are fixed seeds and the clock is the vector's ``nowSeconds``.
Run ``python -m tests.support.resolved_turn_vector`` from ``backend/python`` to rewrite the file; a test holds
the committed file equal to ``build()``.
"""

from __future__ import annotations

import base64
import hashlib
import json
from pathlib import Path
from typing import Any

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from harness_core.testing.gateway import encode_token, kid_for, public_pem

VECTORS = Path(__file__).resolve().parents[4] / "contracts"
VECTOR_PATH = VECTORS / "control-plane" / "vectors" / "resolved-turn.json"
GATEWAY_VECTOR_PATH = VECTORS / "harness" / "vectors" / "gateway-token.json"

ISSUER = "pipeshub-node/agent-harness"
AUDIENCE = "pipeshub-query/resolved-turn"
RETENTION_MS = 15 * 60 * 1000

_DESCRIPTION = (
    "CPD-10 RTE-22 cross-language vector: the X-PipesHub-Resolved header (compact JWS, Ed25519) that Node signs "
    "with the gateway-token keyring under its own audience and the query service verifies. keys.active is "
    "gateway-token.json's test key; keys.retired was retired at retiredAtMs and verifies for retentionMs after "
    "it; keys are JWKs (d = the 32-byte seed), never used outside tests. Node's codec (encodeAttemptToken) must "
    "produce exactly valid.token from valid.header and valid.payload (key order as written), and retired.token "
    "from the same payload under the retired key; both sides accept them at nowSeconds for binding.request. "
    "'refused' holds tokens both sides refuse with `reason` for binding.request at nowSeconds: where a payload "
    "is given the token is that payload signed as written, otherwise `how` says how the bytes were made. A "
    "lifetime over maxLifetimeSeconds, a missing claim and a claim this version does not know are malformed; "
    "`access` and `bindings` are the only optional claims. 'binding.refused' holds the requests valid.token is "
    "refused for. Generated by backend/python/tests/support/resolved_turn_vector.py."
)


def _seed(label: str) -> Ed25519PrivateKey:
    return Ed25519PrivateKey.from_private_bytes(hashlib.sha256(label.encode()).digest())


def _b64(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).rstrip(b"=").decode("ascii")


def _jwk(key: Ed25519PrivateKey) -> dict[str, str]:
    from cryptography.hazmat.primitives.serialization import (
        Encoding,
        NoEncryption,
        PrivateFormat,
        PublicFormat,
    )

    seed = key.private_bytes(Encoding.Raw, PrivateFormat.Raw, NoEncryption())
    public = key.public_key().public_bytes(Encoding.Raw, PublicFormat.Raw)
    return {"kty": "OKP", "crv": "Ed25519", "d": _b64(seed), "x": _b64(public)}


def _published(key: Ed25519PrivateKey, **more: Any) -> dict[str, Any]:  # noqa: ANN401
    return {"kid": kid_for(key), "jwk": _jwk(key), "publicKeyPem": public_pem(key), **more}


def _header(key: Ed25519PrivateKey) -> dict[str, str]:
    return {"alg": "EdDSA", "typ": "JWT", "kid": kid_for(key)}


def _payload(now: int) -> dict[str, Any]:
    return {
        "iss": ISSUER,
        "aud": AUDIENCE,
        "iat": now - 1,
        "exp": now + 59,
        "ver": 1,
        "org": "org-1",
        "sub": "user-1",
        "agent": "agent-a",
        "cid": "conv-1",
        "pin": {
            "digest": "sha256:65052142c701dc852280e6a406cbf15e4b5ba67e6d9d54dd8784b35566c7abc9",
            "head": 41,
            "routing": {"path": "legacy", "reason": "chat_mode_not_supported"},
            "scope": {"agentKey": "agent-a", "projectId": None},
        },
        "stages": {
            "ENABLE_AGENT_HARNESS": True,
            "AGENT_HARNESS_KILL_SWITCH": False,
            "ENABLE_ACTIONS": True,
            "ENABLE_MCP": True,
            "ENABLE_SKILLS": True,
            "ENABLE_USER_CONTEXT": False,
        },
        "flow": [{"level": "ask", "above": "public"}, {"level": "deny", "above": "private"}],
        "access": {"run": True},
        "bindings": [
            {"installation": "inst-jira", "owner": "user:user-1", "ref": "bnd_01J9ZX3K7M2Q4R6T8V0W1Y3Z5A"},
            {"installation": "inst-mcp", "owner": "agent:agent-a", "ref": "bnd_01J9ZX3K7M2Q4R6T8V0W1Y3Z5B"},
        ],
    }


def _without(payload: dict[str, Any], claim: str) -> dict[str, Any]:
    return {name: value for name, value in payload.items() if name != claim}


def _signed(reason: str, case: str, payload: dict[str, Any], key: Ed25519PrivateKey) -> dict[str, Any]:
    return {"id": case, "reason": reason, "payload": payload, "token": encode_token(_header(key), payload, key)}


def build() -> dict[str, Any]:
    gateway = json.loads(GATEWAY_VECTOR_PATH.read_text(encoding="utf-8"))
    now: int = gateway["nowSeconds"]
    active = Ed25519PrivateKey.from_private_bytes(base64.urlsafe_b64decode(gateway["jwk"]["d"] + "="))
    assert kid_for(active) == gateway["kid"]
    retired = _seed("resolved-turn vector: the retired key")
    unpublished = _seed("resolved-turn vector: a key nobody published")
    payload = _payload(now)
    token = encode_token(_header(active), payload, active)
    head, body, signature = token.split(".")
    tampered = encode_token(_header(active), {**payload, "org": "org-2"}, active).split(".")[1]
    none_header = {**_header(active), "alg": "none"}
    request = {"orgId": "org-1", "userId": "user-1", "agentKey": "agent-a", "conversationId": "conv-1"}
    return {
        "description": _DESCRIPTION,
        "issuer": ISSUER,
        "audience": AUDIENCE,
        "version": 1,
        "ttlSeconds": 60,
        "maxLifetimeSeconds": 120,
        "maxTokenLength": 16384,
        "retentionMs": RETENTION_MS,
        "nowSeconds": now,
        "keys": {
            "active": _published(active),
            "retired": _published(retired, retiredAtMs=(now - 60) * 1000),
        },
        "valid": {"header": _header(active), "payload": payload, "token": token},
        "retired": {"header": _header(retired), "payload": payload, "token": encode_token(_header(retired), payload, retired)},
        "refused": [
            _signed("resolved_unknown_key", "unknown-kid", payload, unpublished),
            _signed("resolved_expired", "expired", {**payload, "iat": now - 61, "exp": now - 1}, active),
            {
                "id": "tampered-payload",
                "reason": "resolved_signature",
                "how": "valid.payload with org 'org-2', re-encoded, under valid.token's header and signature",
                "token": f"{head}.{tampered}.{signature}",
            },
            {
                "id": "tampered-signature",
                "reason": "resolved_signature",
                "how": "valid.token with the first character of its signature replaced",
                "token": f"{head}.{body}.{'B' if signature[0] == 'A' else 'A'}{signature[1:]}",
            },
            {
                "id": "alg-none",
                "reason": "resolved_algorithm",
                "how": "valid.token with alg 'none' in its header; the signature segment is kept (an empty one is malformed)",
                "header": none_header,
                "token": f"{encode_token(none_header, payload, active).split('.')[0]}.{body}.{signature}",
            },
            {
                "id": "gateway-token",
                "reason": "resolved_audience",
                "how": "gateway-token.json's run token: the same keyring and issuer, the gateway's audience",
                "token": gateway["tokens"][0]["token"],
            },
            _signed("resolved_issuer", "wrong-issuer", {**payload, "iss": "pipeshub-node/other"}, active),
            _signed("resolved_malformed", "lifetime-too-long", {**payload, "exp": payload["iat"] + 121}, active),
            _signed("resolved_version", "unknown-version", {**payload, "ver": 2}, active),
            _signed(
                "resolved_routing",
                "durable-routing",
                {**payload, "pin": {**payload["pin"], "routing": {"path": "durable", "reason": None}}},
                active,
            ),
            _signed("resolved_malformed", "missing-claim", _without(payload, "cid"), active),
            _signed("resolved_malformed", "extra-claim", {**payload, "role": "admin"}, active),
        ],
        "binding": {
            "request": request,
            "refused": [
                {"id": "another-org", "reason": "resolved_subject_mismatch", "request": {**request, "orgId": "org-2"}},
                {"id": "another-user", "reason": "resolved_subject_mismatch", "request": {**request, "userId": "user-2"}},
                {"id": "another-agent", "reason": "resolved_agent_mismatch", "request": {**request, "agentKey": "agent-b"}},
                {"id": "the-assistant", "reason": "resolved_agent_mismatch", "request": {**request, "agentKey": None}},
                {
                    "id": "another-conversation",
                    "reason": "resolved_conversation_mismatch",
                    "request": {**request, "conversationId": "conv-2"},
                },
                {
                    "id": "no-conversation",
                    "reason": "resolved_conversation_mismatch",
                    "request": {**request, "conversationId": None},
                },
            ],
        },
    }


def render() -> str:
    return json.dumps(build(), indent=2) + "\n"


if __name__ == "__main__":
    VECTOR_PATH.write_text(render(), encoding="utf-8")

"""Typed constants from the contracts, rendered for Python and TypeScript.

Two sources, so no language hand-copies a value set or a code:

- a ``$defs`` entry carrying ``x-constant`` is a string enumeration; it becomes a type and a
  tuple (``SuspendReason`` / ``SUSPEND_REASONS``) in its group's ``enums`` module;
- a group's ``errors.json`` (an ``ErrorCatalog``) becomes its ``errors`` module: ``ERROR_CODES``
  keyed by code, ``ErrorCode``, and ``WIRE_PREFIX``.
"""

from __future__ import annotations

import json
import re
from collections.abc import Callable
from dataclasses import dataclass
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from pathlib import Path

HEADER_PY = "# generated by contracts/harness/codegen/generate.py -- do not edit\n"
HEADER_TS = "// generated by contracts/harness/codegen/generate.py -- do not edit\n/* eslint-disable */\n"
ERRORS_FILE = "errors.json"
ERROR_CATALOG_SCHEMA = "error-catalog.schema.json"
ERROR_ENTRY_MODEL = "harness_core.contracts.generated.error_catalog"

_CONSTANT = re.compile(r"^[A-Z][A-Z0-9_]*$")
_TYPE_NAME = re.compile(r"^[A-Z][A-Za-z0-9]*$")
_ENUM_KEYS = frozenset({"enum", "x-constant", "description", "type", "title", "x-extensible-enum"})


Resolve = Callable[["Path", str], tuple["Path", str, dict[str, Any]]]


class ConstantsError(ValueError):
    """A contract file the constants cannot be taken from; names the file and the key."""


@dataclass(frozen=True)
class EnumConstant:
    type_name: str
    constant: str
    values: tuple[str, ...]
    description: str | None


@dataclass(frozen=True)
class DataConstant:
    """A data file emitted as one typed constant: ``module`` is its schema's module, relative to the group."""

    constant: str
    title: str
    module: str
    data: Any
    python: bool = True
    # TypeScript's type for it when it is not the schema's type itself.
    ts_type: str | None = None


@dataclass(frozen=True)
class GroupConstants:
    enums: tuple[EnumConstant, ...]
    errors: dict[str, Any] | None
    data: tuple[DataConstant, ...] = ()

    @property
    def empty(self) -> bool:
        return not self.enums and self.errors is None and not self.data


def enum_constants(
    schemas: list[Path], resolve: Resolve | None = None, load: Callable[[Path], dict[str, Any]] | None = None
) -> tuple[EnumConstant, ...]:
    """Every ``x-constant`` enumeration of one group; a name or constant declared twice is refused.

    A ``$defs`` entry that names its enumeration by ``$ref`` re-exports the referenced one (``resolve`` finds it), so
    one enumeration serves two groups without a copy; it must keep the referenced type name and constant."""
    found: list[EnumConstant] = []
    for path in schemas:
        doc = load(path) if load is not None else json.loads(path.read_text(encoding="utf-8"))
        for name, node in doc.get("$defs", {}).items():
            if "x-constant" not in node:
                continue
            enum = _referenced_enum(path, name, node, resolve) if "$ref" in node else _enum(path, name, node)
            if any(e.constant == enum.constant or e.type_name == enum.type_name for e in found):
                raise ConstantsError(f"{path.name}: $defs/{name}: {enum.type_name} / {enum.constant} is declared twice")
            found.append(enum)
    return tuple(sorted(found, key=lambda e: e.constant))


def _referenced_enum(path: Path, name: str, node: dict[str, Any], resolve: Resolve | None) -> EnumConstant:
    where = f"{path.name}: $defs/{name}"
    if resolve is None or set(node) - {"$ref", "x-constant", "description"}:
        raise ConstantsError(f"{where}: an x-constant $ref carries only $ref, x-constant and description")
    target_path, target_name, target = resolve(path, node["$ref"])
    enum = _enum(target_path, target_name, target)
    if (enum.type_name, enum.constant) != (name, node["x-constant"]):
        raise ConstantsError(f"{where}: re-exports {enum.type_name} / {enum.constant} under another name")
    return enum


def _enum(path: Path, name: str, node: dict[str, Any]) -> EnumConstant:
    where = f"{path.name}: $defs/{name}"
    constant = node["x-constant"]
    values = node.get("enum")
    if not isinstance(constant, str) or not _CONSTANT.match(constant):
        raise ConstantsError(f"{where}: x-constant must be UPPER_SNAKE, got {constant!r}")
    if not _TYPE_NAME.match(name):
        raise ConstantsError(f"{where}: the $defs name is the type name and must be PascalCase")
    if set(node) - _ENUM_KEYS or node.get("type", "string") != "string":
        raise ConstantsError(f"{where}: x-constant applies to a plain string enum only")
    if not isinstance(values, list) or not values or not all(isinstance(v, str) for v in values):
        raise ConstantsError(f"{where}: x-constant needs a non-empty enum of strings")
    if len(set(values)) != len(values):
        raise ConstantsError(f"{where}: enum repeats a value")
    return EnumConstant(name, constant, tuple(values), node.get("description"))


def error_catalog(group_dir: Path, catalog_schema: dict[str, Any]) -> dict[str, Any] | None:
    path = group_dir / ERRORS_FILE
    if not path.exists():
        return None
    from jsonschema import Draft202012Validator

    data = json.loads(path.read_text(encoding="utf-8"))
    errors = sorted(Draft202012Validator(catalog_schema).iter_errors(data), key=lambda e: str(list(e.absolute_path)))
    if errors:
        first = errors[0]
        where = "/".join(str(p) for p in first.absolute_path) or "(root)"
        raise ConstantsError(f"{path}: {where}: {first.message}")
    codes = [entry["code"] for entry in data["codes"]]
    if len(set(codes)) != len(codes):
        raise ConstantsError(f"{path}: codes: a code repeats")
    return data


def _py_literal(values: tuple[str, ...] | list[str]) -> str:
    return "Literal[" + ", ".join(json.dumps(v) for v in values) + "]"


def _py_tuple(values: tuple[str, ...] | list[str]) -> str:
    inner = ", ".join(json.dumps(v) for v in values)
    return f"({inner},)" if len(values) == 1 else f"({inner})"


def render_enums_py(enums: tuple[EnumConstant, ...]) -> str:
    lines = [HEADER_PY, "from __future__ import annotations", "", "from typing import Final, Literal", ""]
    for e in enums:
        if e.description:
            lines.append(f"# {e.description}")
        lines.append(f"{e.type_name} = {_py_literal(e.values)}")
        lines.append(f"{e.constant}: Final[tuple[{e.type_name}, ...]] = {_py_tuple(e.values)}")
        lines.append("")
    lines.append("__all__ = [" + ", ".join(json.dumps(n) for e in enums for n in (e.constant, e.type_name)) + "]")
    return "\n".join(lines) + "\n"


def render_enums_ts(enums: tuple[EnumConstant, ...]) -> str:
    lines = [HEADER_TS]
    for e in enums:
        if e.description:
            lines.append(f"/** {e.description} */")
        values = ", ".join(json.dumps(v) for v in e.values)
        lines.append(f"export const {e.constant} = Object.freeze([{values}] as const);")
        lines.append(f"export type {e.type_name} = (typeof {e.constant})[number];")
        lines.append("")
    return "\n".join(lines)


def _entry_wire(entry: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in entry.items() if k != "code"}


def render_errors_py(catalog: dict[str, Any]) -> str:
    codes = [entry["code"] for entry in catalog["codes"]]
    lines = [
        HEADER_PY,
        "from __future__ import annotations",
        "",
        "from types import MappingProxyType",
        "from typing import TYPE_CHECKING, Final, Literal",
        "",
        f"from {ERROR_ENTRY_MODEL} import ErrorCatalogEntry",
        "",
        "if TYPE_CHECKING:",
        "    from collections.abc import Mapping",
        "",
        f"WIRE_PREFIX: Final = {json.dumps(catalog.get('wirePrefix', ''))}",
        "",
        f"ErrorCode = {_py_literal(codes)}",
        "",
        "ERROR_CODES: Final[Mapping[ErrorCode, ErrorCatalogEntry]] = MappingProxyType({",
    ]
    for entry in catalog["codes"]:
        lines.append(f"    {json.dumps(entry['code'])}: ErrorCatalogEntry.model_validate({entry!r}),")
    lines += ["})", "", '__all__ = ["ERROR_CODES", "WIRE_PREFIX", "ErrorCode"]', ""]
    return "\n".join(lines)


def render_errors_ts(catalog: dict[str, Any]) -> str:
    lines = [
        HEADER_TS,
        f"export const WIRE_PREFIX = {json.dumps(catalog.get('wirePrefix', ''))};",
        "",
        "export const ERROR_CODES = Object.freeze({",
    ]
    for entry in catalog["codes"]:
        lines.append(f"  {entry['code']}: {json.dumps(_entry_wire(entry), ensure_ascii=False)},")
    lines += [
        "} as const);",
        "",
        "export type ErrorCode = keyof typeof ERROR_CODES;",
        "/** The codes of one `group` of the catalogue. */",
        "export type ErrorCodeOf<G extends string> = {",
        "  [K in ErrorCode]: (typeof ERROR_CODES)[K] extends { readonly group: G } ? K : never;",
        "}[ErrorCode];",
        "",
    ]
    return "\n".join(lines)


DATA_MODULE = "policy_data"


def _json_literal(data: Any) -> str:  # noqa: ANN401 - a JSON document
    # A JSON string literal is a valid Python one.
    return json.dumps(json.dumps(data, separators=(",", ":"), ensure_ascii=False), ensure_ascii=False)


def render_data_py(data: tuple[DataConstant, ...], package: str) -> str:
    emitted = [d for d in data if d.python]
    lines = [HEADER_PY, "from __future__ import annotations", "", "from typing import Final", ""]
    lines.extend(
        f"from {package}.{d.module.replace('/', '.').replace('-', '_')} import {d.title}"
        for d in sorted(emitted, key=lambda d: d.module)
    )
    lines.append("")
    lines.extend(f"{d.constant}: Final = {d.title}.model_validate_json({_json_literal(d.data)})" for d in emitted)
    lines += ["", "__all__ = [" + ", ".join(json.dumps(d.constant) for d in emitted) + "]", ""]
    return "\n".join(lines)


def render_data_ts(data: tuple[DataConstant, ...]) -> str:
    lines = [HEADER_TS]
    lines.extend(f"import type {{ {title} }} from './{module}';" for title, module in sorted({(d.title, d.module) for d in data}))
    lines += [
        "",
        "const deepFreeze = <T>(value: T): T => {",
        "  if (typeof value === 'object' && value !== null) {",
        "    for (const member of Object.values(value)) deepFreeze(member);",
        "    Object.freeze(value);",
        "  }",
        "  return value;",
        "};",
        "",
    ]
    for d in data:
        literal = json.dumps(d.data, indent=2, ensure_ascii=False)
        lines.append(f"export const {d.constant} = deepFreeze<{d.ts_type or d.title}>({literal});")
        lines.append("")
    return "\n".join(lines)


def python_modules(constants: GroupConstants, package: str = "") -> dict[str, str]:
    out: dict[str, str] = {}
    if constants.enums:
        out["enums.py"] = render_enums_py(constants.enums)
    if constants.errors is not None:
        out["errors.py"] = render_errors_py(constants.errors)
    if any(d.python for d in constants.data):
        out[f"{DATA_MODULE}.py"] = render_data_py(constants.data, package)
    return out


def ts_modules(constants: GroupConstants) -> dict[str, str]:
    out: dict[str, str] = {}
    if constants.enums:
        out["enums.ts"] = render_enums_ts(constants.enums)
    if constants.errors is not None:
        out["errors.ts"] = render_errors_ts(constants.errors)
    if constants.data:
        out[f"{DATA_MODULE.replace('_', '-')}.ts"] = render_data_ts(constants.data)
    return out

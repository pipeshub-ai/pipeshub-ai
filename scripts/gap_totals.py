#!/usr/bin/env python3
"""Generate the gap totals line of docs/test-plan/05-traceability-and-gaps.md from data/gaps.tsv.

    scripts/gap_totals.py           # rewrite the totals between the gap-totals markers
    scripts/gap_totals.py --check   # non-zero if the totals are stale or the appendix disagrees with gaps.tsv

The status column of gaps.tsv is the one source. A status starts with its state (`open`, `closed`, `partial`
or `partly closed`); a closed or partial status names the work package that closed it as its first WP id
(`closed (QA-4)`, `partial: CPS PN-6 ...`). The appendix of 05 repeats each status, and --check requires the
two to agree, so a WP that updates one and not the other is caught at the merge queue.

Standard library only.
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GAPS = ROOT / "docs/test-plan/data/gaps.tsv"
DOC = ROOT / "docs/test-plan/05-traceability-and-gaps.md"
BEGIN = "<!-- gap-totals:begin (generated by scripts/gap_totals.py; edit data/gaps.tsv) -->"
END = "<!-- gap-totals:end -->"
APPENDIX = "## Appendix: every gap"

# QA8-9 and QA27-F4 are case ids, not WPs: a WP id has no dash or word character on either side.
# A follow-up WP takes a letter (QA-15F).
WP_ID = re.compile(r"(?<![-\w])(CPS|MCP-E2E|MCPFIX|CPD-\d+|QA-\d+[A-Z]?|PERF-[A-Z]|[A-Z]{1,4}\d+[a-z]?)(?![-\w])")
STATES = (("partly closed", "partial"), ("partial", "partial"), ("closed", "closed"), ("open", "open"))


class GapStatusError(ValueError):
    pass


@dataclass(frozen=True)
class Status:
    state: str
    wp: str | None


def parse_status(gap: str, text: str) -> Status:
    lowered = text.strip().lower()
    for prefix, state in STATES:
        if lowered.startswith(prefix):
            break
    else:
        raise GapStatusError(f"{gap}: status {text!r} does not start with open, closed, partial or partly closed")
    if state == "open":
        return Status("open", None)
    m = WP_ID.search(text)
    if m is None:
        raise GapStatusError(f"{gap}: {state} status {text!r} names no work package")
    return Status(state, m.group(1))


def read_gaps(path: Path = GAPS) -> dict[str, str]:
    with path.open(encoding="utf-8", newline="") as fh:
        return {row["gap"]: row["status"] for row in csv.DictReader(fh, delimiter="\t")}


def wp_sort_key(wp: str) -> tuple[tuple[int, int, str], ...]:
    """Natural order of WP ids: QA-4 before QA-10, P4.9 before P4.10."""
    return tuple((0, int(p), "") if p.isdigit() else (1, 0, p) for p in re.split(r"(\d+)", wp.lower()))


def totals_text(statuses: dict[str, str]) -> str:
    parsed = {gap: parse_status(gap, s) for gap, s in statuses.items()}
    closed = Counter(st.wp for st in parsed.values() if st.state == "closed")
    partial = Counter(st.wp for st in parsed.values() if st.state == "partial")
    parts = []
    for wp in sorted({st.wp for st in parsed.values() if st.wp}, key=wp_sort_key):
        bits = []
        if closed[wp]:
            bits.append(f"{closed[wp]} closed")
        if partial[wp]:
            bits.append(f"{partial[wp]} partly closed")
        parts.append(f"{' and '.join(bits)} by {wp}")
    not_closed = sum(1 for st in parsed.values() if st.state != "closed")
    by_wp = ", ".join(parts) if parts else "none closed"
    return f"{len(parsed)} found; {by_wp}; {not_closed} not closed, partly closed included (`data/gaps.tsv`)"


def render(doc: str, statuses: dict[str, str]) -> str:
    pattern = re.compile(re.escape(BEGIN) + ".*?" + re.escape(END))
    if len(pattern.findall(doc)) != 1:
        raise GapStatusError(f"{DOC.name} must hold exactly one {BEGIN} ... {END} span")
    return pattern.sub(lambda _: BEGIN + totals_text(statuses) + END, doc)


def appendix_statuses(doc: str) -> dict[str, str]:
    if APPENDIX not in doc:
        return {}
    out = {}
    for line in doc.split(APPENDIX, 1)[1].splitlines():
        m = re.match(r"^\| ([A-Za-z0-9]+-G\d+) \|", line)
        if m:
            out[m.group(1)] = line.strip().strip("|").split("|")[-1].strip()
    return out


def disagreements(doc: str, statuses: dict[str, str]) -> list[str]:
    shown = appendix_statuses(doc)
    out = [f"{g}: in gaps.tsv, not in the appendix" for g in statuses if g not in shown]
    out += [f"{g}: in the appendix, not in gaps.tsv" for g in shown if g not in statuses]
    out += [f"{g}: gaps.tsv {statuses[g]!r} != appendix {shown[g]!r}"
            for g in statuses if g in shown and shown[g] != statuses[g]]
    return out


def check(doc_path: Path = DOC, gaps_path: Path = GAPS) -> list[str]:
    doc = doc_path.read_text(encoding="utf-8")
    statuses = read_gaps(gaps_path)
    problems = disagreements(doc, statuses)
    try:
        if render(doc, statuses) != doc:
            problems.append(f"stale gap totals in {doc_path.name} (run scripts/gap_totals.py)")
    except GapStatusError as e:
        problems.append(str(e))
    return problems


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if the totals are stale or the appendix disagrees")
    args = ap.parse_args(argv)
    if args.check:
        problems = check()
        for p in problems:
            print(p, file=sys.stderr)
        return 1 if problems else 0
    doc = DOC.read_text(encoding="utf-8")
    statuses = read_gaps()
    try:
        new = render(doc, statuses)
    except GapStatusError as e:
        print(e, file=sys.stderr)
        return 1
    if new != doc:
        DOC.write_text(new, encoding="utf-8")
    print(totals_text(statuses))
    return 0


if __name__ == "__main__":
    sys.exit(main())
